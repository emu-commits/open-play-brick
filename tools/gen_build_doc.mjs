// Fills in the parts list and the wiring table in site/BUILD.md from
// site/data/netlist.json, between the BEGIN/END markers.
// Run with --check to fail if the committed guide is out of date.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const n = JSON.parse(readFileSync(join(root, 'site/data/netlist.json'), 'utf8'));
const file = join(root, 'site/BUILD.md');

const usd = v => (v ? `$${v.toFixed(2)}` : '');

// ---- parts list ----
let total = 0, optional = 0;
let parts = '| Qty | Part | What to order | About | Notes |\n| --- | --- | --- | --- | --- |\n';
for (const p of n.parts.filter(p => p.buy)) {
  const b = p.buy;
  if (b.optional) optional += b.usd; else total += b.usd;
  parts += `| 1 | ${b.item}${b.optional ? ' *(optional)*' : ''} | ${b.sku} | ${usd(b.usd)} | ${p.role}. ${b.note ?? ''} |\n`;
}
for (const e of n.extras) {
  total += e.usd * e.qty;
  parts += `| ${e.qty} | ${e.item} | ${e.sku} | ${usd(e.usd * e.qty)} | ${e.note ?? ''} |\n`;
}
parts += `\nAbout **$${Math.round(total)}** before shipping, or $${Math.round(total + optional)} with the optional part. Prices checked ${n.prices_checked}.\n`;

// ---- wiring table ----
function destination(part, pin, net) {
  if (part.to?.[pin]) return part.to[pin];
  const pad = n.feather_pad[net];
  if (!pad) return net;
  const gpio = n.gpio[net];
  return gpio != null ? `Feather **${pad}** (GPIO${gpio})` : `Feather **${pad}**`;
}
let wiring = '| Board | Its pad | Connect to | Signal |\n| --- | --- | --- | --- |\n';
for (const p of n.parts.filter(p => p.buy && p.pads)) {
  // Rows that share a pad and a destination (a 4-wire cable) become one row.
  const rows = [];
  for (const [pin, net] of p.pins) {
    const pad = p.pads[pin];
    if (!pad) continue;
    const to = destination(p, pin, net);
    const same = rows.find(r => r.pad === pad && r.to === to);
    if (same) same.nets.push(net);
    else rows.push({ pad, to, nets: [net] });
  }
  rows.forEach((r, i) => {
    wiring += `| ${i ? '' : `**${p.name}** (${p.role})`} | ${r.pad} | ${r.to} | ${r.nets.join(', ')} |\n`;
  });
}

const block = (name, body) => `<!-- BEGIN:${name} (generated by tools/gen_build_doc.mjs, do not edit) -->\n${body}<!-- END:${name} -->`;
const fill = (text, name, body) => {
  const re = new RegExp(`<!-- BEGIN:${name}[^>]*-->[\\s\\S]*?<!-- END:${name} -->`);
  if (!re.test(text)) throw new Error(`BUILD.md has no ${name} markers`);
  return text.replace(re, block(name, body));
};

const before = readFileSync(file, 'utf8');
const after = fill(fill(before, 'parts', parts), 'wiring', wiring);
if (process.argv.includes('--check')) {
  if (before !== after) { console.error('site/BUILD.md is out of date: run node tools/gen_build_doc.mjs'); process.exit(1); }
  console.log('BUILD.md matches netlist.json');
} else {
  writeFileSync(file, after);
  console.log('updated', file);
}
